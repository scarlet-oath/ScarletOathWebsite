export function SocialIcon({path, src, viewBox = '0 0 24 24'}) {
    if (src) {
        return <img className="size-5 shrink-0" src={src} alt=""/>
    }

    return (
        <svg className="size-5 shrink-0 fill-current" viewBox={viewBox} aria-hidden="true">
            <path d={path}/>
        </svg>
    )
}